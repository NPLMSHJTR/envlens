"""Writers for the two repairing commands.

Both commands are additive by design. ``init`` creates a new example file;
``fix`` appends keys that are missing from an existing one. Neither command
rewrites, reorders, or deletes existing lines, because an example file usually
carries hand-written comments that explain where a value comes from, and a tool
that silently reformats them is a tool people stop running.
"""

from __future__ import annotations

from pathlib import Path

from . import __version__
from .model import Reference

HEADER = f"""# Environment variables for this project.
#
# Generated by envlens {__version__}. This file is the contract that `envlens check`
# validates against the source code, so keep it in sync when you add a variable.
# Never put real credentials in this file.
"""

APPEND_HEADER = f"""
# Added by envlens {__version__}: read in code but missing above.
"""


def _comment_for(refs: list[Reference], limit: int = 2) -> str:
    locations = [ref.location for ref in refs[:limit]]
    suffix = f" (+{len(refs) - limit} more)" if len(refs) > limit else ""
    return "# used in " + ", ".join(locations) + suffix


def render_example(used: dict[str, list[Reference]], extra_keys: list[str] | None = None) -> str:
    """Build a fresh example file from the keys the code reads."""
    keys = sorted(set(used) | set(extra_keys or []))
    blocks = [HEADER]
    for key in keys:
        refs = used.get(key, [])
        if refs:
            blocks.append(_comment_for(refs))
        blocks.append(f"{key}=")
    return "\n".join(blocks).rstrip() + "\n"


def render_append(missing: list[str], used: dict[str, list[Reference]]) -> str:
    """Build the block that ``fix`` appends for keys missing from the contract."""
    if not missing:
        return ""
    blocks = [APPEND_HEADER.rstrip("\n")]
    for key in sorted(missing):
        refs = used.get(key, [])
        if refs:
            blocks.append(_comment_for(refs))
        blocks.append(f"{key}=")
    return "\n".join(blocks) + "\n"


def write_example(path: Path, content: str, force: bool) -> str:
    """Write ``content`` to ``path``. Returns ``created``, ``overwritten``, or ``skipped``."""
    if path.exists() and not force:
        return "skipped"
    existed = path.exists()
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(content, encoding="utf-8", newline="\n")
    return "overwritten" if existed else "created"


def append_to_example(path: Path, content: str) -> None:
    """Append ``content`` to ``path``, normalising the trailing newline first."""
    existing = path.read_text(encoding="utf-8", errors="replace")
    separator = "" if existing.endswith("\n") else "\n"
    if existing.strip():
        separator = "\n"
    with path.open("a", encoding="utf-8", newline="\n") as handle:
        handle.write(separator + content)
